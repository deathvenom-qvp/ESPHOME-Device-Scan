def test_header_can_be_disabled(cloudbay_template, device) -> None:
    gen = YamlGenerator(add_header=False)
    assert not gen.generate(cloudbay_template, device).content.startswith("#" " Generated")


def test_document_marker_stays_first(generator, device) -> None:
    out = generator.generate(template("---\nesphome:\n  name: x\n"), device)
    assert out.content.startswith("---\n# Generated by ESPHome Device Scan")


def test_output_always_ends_with_a_newline(generator, device) -> None:
    out = generator.generate(template("esphome:\n  name: x"), device)
    assert out.content.endswith("\n")


# -- error handling ---------------------------------------------------------


def test_malformed_template_raises_a_clear_error(generator, device) -> None:
    with pytest.raises(YamlParseError):
        generator.generate(template("esphome:\n  name: [unclosed\n"), device)


def test_empty_template_raises(generator, device) -> None:
    with pytest.raises(YamlParseError, match="empty"):
        generator.generate(template("# just a comment\n"), device)


def test_template_without_an_esphome_block_warns(generator, device) -> None:
    out = generator.generate(template("logger:\n  level: INFO\n"), device)
    assert any("no 'esphome:' block" in w for w in out.warnings)
    assert "logger:" in out.content


def test_template_without_a_name_key_warns(generator, device) -> None:
    out = generator.generate(template("esphome:\n  friendly_name: Thing\n"), device)
    assert any("no 'name:' key" in w for w in out.warnings)


def test_switchboard_template_round_trip(switchboard_template, generator) -> None:
    device = Device(
        node_name="switchboard-hallway", mac="112233445566", status=DeviceStatus.ONLINE
    )
    out = generator.generate(switchboard_template, device)

    assert "name: switchboard-hallway" in out.content
    assert "name_add_mac_suffix: false" in out.content
    assert 'ssid: "Switchboard Fallback"' in out.content  # untouched
    assert out.content.count("platform: gpio") == 4
    assert load(out.content)["esphome"]["name"] == "switchboard-hallway"
